const PROVIDER_ICONS: Record<string, () => React.ReactElement> = {
  google: GoogleIcon,
  github: GitHubIcon,
};

const PROVIDER_LABELS: Record<string, string> = {
  google: 'Google',
  github: 'GitHub',
};

type OAuthProviderButtonsProps = {
  returnTo: string;
};

export default function OAuthProviderButtons({ returnTo }: Readonly<OAuthProviderButtonsProps>) {
  const { t } = useTranslation();
  const providers = useOAuthProviders();

  if (providers.length === 0) return null;

  return (
    <div className={styles.wrapper}>
      <div className={styles.divider}>
        <span>{t('auth.oauth.divider')}</span>
      </div>
      <div className={styles.buttons}>
        {providers.map((provider) => {
          const Icon = PROVIDER_ICONS[provider];
          return (
            <a
              key={provider}
              href={oauthStartUrl(provider, returnTo)}
              className={`btn ${styles.providerButton}`}
            >
              {Icon ? <Icon /> : null}
              {t('auth.oauth.continueWith', { provider: PROVIDER_LABELS[provider] ?? provider })}
            </a>
          );
        })}
      </div>
    </div>
  );
}
